// Helper
function getSten(score: number, ranges: Range[]): number {
  if (!ranges) return 0;
  for (let i = 0; i < ranges.length; i++) {
    if (score >= ranges[i][0] && score <= ranges[i][1]) {
      return i + 1;
    }
  }
  return 0; // Out of range (?)
}

function calculateDetailedPercentile(rawScore: number, sten: number, ranges: Range[]): string {
    const range = ranges[sten - 1]; // ranges is 0-indexed, sten is 1-indexed
    if (!range) return "-";
    const [min, max] = range;

    const stenBoundaries = STEN_PERCENTILE_RANGES[sten - 1]; // 0-indexed
    if (!stenBoundaries) return "-";
    const [pMin, pMax] = stenBoundaries;
    
    // Calculate position of raw score within the raw range.
    // If range width is 0 (min=max), we assume it's the center percentile of that sten, or just the range.
    let ratio = 0.5;
    if (max > min) {
        ratio = (rawScore - min) / (max - min);
    }
    
    // Interpolate percentile
    const preciseP = pMin + ratio * (pMax - pMin);
    
    return preciseP.toFixed(1) + "%";
}

export function calculateSten(
  type: 'trait' | 'facet',
  code: string,
  rawScore: number,
  sex: 'female' | 'male',
  age: number
): { sten: number; percentile: string } {
  const isOver30 = age >= 30;
  let ranges: Range[] | undefined;

  if (type === 'trait') {
    if (sex === 'female') {
      ranges = isOver30 ? women_30_plus_traits[code] : women_under_30_traits[code];
    } else {
      ranges = isOver30 ? men_30_plus_traits[code] : men_under_30_traits[code];
    }
  } else {
    // Facet
    // Note: CSV provided only seems to separate by sex for facets, not age. 
    // The "Women" and "Men" blocks for facets didn't have sub-headers for age.
    // So we use sex only.
    if (sex === 'female') {
      ranges = women_facets[code];
    } else {
      ranges = men_facets[code];
    }
  }

  const sten = getSten(rawScore, ranges);
  // If sten is 0, it means score was out of known bounds (or logic error). 
  // We'll return 0 and empty percentile.
  
  if (sten === 0 || !ranges) return { sten: 0, percentile: '-' };
  
  const percentile = calculateDetailedPercentile(rawScore, sten, ranges);
  
  return { 
    sten, 
    percentile
  };
}
